// Bundles the inspector page (src/inspector/page.ts + page.css) into a generated TypeScript module
// so `createMcpAppServer({ inspector: true })` can serve it from a single string with no static files.
// Runs before tsc; the output is gitignored.
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';

const bundled = await build({ entryPoints: ['src/inspector/page.ts'], bundle: true, write: false, format: 'iife', target: 'es2022', minify: true });
const style = await readFile('src/inspector/page.css', 'utf8');
const literal = (text) => JSON.stringify(text).replace(/<\//g, '<\\/');
await writeFile(
  'src/inspector/bundle.generated.ts',
  `// Generated by scripts/build-inspector.mjs — do not edit.\nexport const script: string = ${literal(bundled.outputFiles[0].text)};\nexport const style: string = ${literal(style)};\n`,
);
